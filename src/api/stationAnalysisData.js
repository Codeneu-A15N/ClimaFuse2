/**
 * Returns station analysis data for a given city ID, or fallback to delhi.
 */
export function getStationAnalysis(cityId) {
  if (!cityId) return STATION_ANALYSIS_DATA.delhi;
  const key = cityId.toLowerCase();
  return STATION_ANALYSIS_DATA[key] || STATION_ANALYSIS_DATA.delhi;
}

/**
 * Generates and triggers download of CSV formatted telemetry.
 */
export function exportStationCSV(station) {
  if (!station) return;
  const headers = ['Time', 'Observed_Temp_C', 'ClimaFuse_BMA_Temp_C', 'ECMWF_IFS_Temp_C', 'AIFS_AI_Temp_C', 'Observed_HeatIndex_C', 'ClimaFuse_HeatIndex_C', 'Rain_BMA_mm', 'Rain_Obs_mm'];
  const rows = station.timeseries.map((t) => [
    t.time,
    t.obs,
    t.bma,
    t.ifs,
    t.aifs,
    t.hiObs,
    t.hiBma,
    t.rainBma,
    t.rainObs,
  ]);

  const csvContent = [headers.join(','), ...rows.map((r) => r.join(','))].join('\n');
  const blob = new Blob([csvContent], { type: 'text/csv;charset=utf-8;' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.setAttribute('href', url);
  link.setAttribute('download', `ClimaFuse_${station.name.replace(/\s+/g, '_')}_${station.wmoId}_telemetry.csv`);
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}
